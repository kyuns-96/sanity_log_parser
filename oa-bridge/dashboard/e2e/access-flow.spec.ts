const path = '/?demo=1&flow=access'

test('role switching scopes every project, block and count without backend calls', async ({ page }) => {
  const requests: string[] = []
  const errors: string[] = []
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) requests.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(path)
  await expect(page.getByRole('button', { name: '프로젝트 만들기', exact: true })).toBeVisible()
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.getByRole('button', { name: '이영희 계정으로 전환' }).click()
  await expect(page.getByRole('article')).toHaveCount(3)
  await expect(page.getByRole('button', { name: 'Boreal 프로젝트 선택' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '프로젝트 만들기', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '담당자 설정', exact: true })).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: '워크스페이스 메뉴' })).not.toContainText('담당자 배정')
  await page.getByRole('button', { name: '김철수 계정으로 전환' }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('article', { name: 'CPU 블록' })).toBeVisible()
  await expect(page.locator('.af-stats')).toContainText('조회 가능한 블록2개')
  await page.getByRole('button', { name: 'Boreal 프로젝트 선택' }).click()
  await expect(page.getByRole('article', { name: 'DDR 블록' })).toBeVisible()
  await expect(page.getByRole('article', { name: 'CPU 블록' })).toHaveCount(0)
  await page.getByRole('button', { name: '최지우 계정으로 전환' }).click()
  await expect(page.getByRole('heading', { name: '아직 배정된 프로젝트가 없습니다' })).toBeVisible()
  await expect(page.getByRole('region', { name: '프로젝트 목록' })).toHaveCount(0)
  expect(requests).toEqual([])
  expect(errors).toEqual([])
})

