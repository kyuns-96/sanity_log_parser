test('demo mutations reject unauthorized and cross-project grants', () => {
  const state = initialAccessState()
  expect(() => createDemoProject(state, person('u-lee'), newProjectDraft())).toThrow('프로젝트 생성 권한')
  expect(() => saveDemoGrants(state, person('u-kim'), 'p-atlas', state.grants)).toThrow('관리 권한')
  const atlas = state.grants.filter(grant => grant.projectId === 'p-atlas')
  expect(() => saveDemoGrants(state, person('u-admin'), 'p-atlas', [...atlas, { userId: 'u-choi', projectId: 'p-atlas', scope: 'block', role: 'reviewer', blockId: 'boreal-ddr' }])).toThrow('담당 범위')
  const withManager = saveDemoGrants(state, person('u-admin'), 'p-atlas', [...atlas, { userId: 'u-lee', projectId: 'p-atlas', scope: 'project', role: 'manager' }])
  expect(() => saveDemoGrants(withManager, person('u-lee'), 'p-boreal', state.grants.filter(grant => grant.projectId === 'p-boreal'))).toThrow('관리 권한')
  expect(visibleBlocks(withManager, person('u-lee'), state.projects[1])).toEqual([])
})
