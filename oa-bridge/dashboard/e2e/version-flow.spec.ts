test('designation rejects TOP, unassigned, foreign block and foreign project attempts', () => {
  const state = initialVersionState()
  const before = structuredClone(state)
  for (const actor of ['u-lee', 'u-choi', 'missing-user', 'u-park']) {
    expect(() => assignPor(state, actor, 'set-cpu-post-0')).toThrow('이 블록의 담당자만')
  }
  expect(() => assignPor(state, 'u-kim', 'set-gpu-post-0')).toThrow('이 블록의 담당자만')
  expect(() => assignPor(state, 'u-kim', 'missing-set')).toThrow('세트를 찾을 수 없습니다')
  const foreign = { ...state, revisionSets: [...state.revisionSets, { ...revisionSetOf(state, 'set-cpu-post-0'), id: 'foreign-set', projectId: 'p-boreal' }] }
  expect(() => assignPor(foreign, 'u-kim', 'foreign-set')).toThrow('이 블록의 담당자만')
  expect(state).toEqual(before)
  expect(visibleVersionBlocks('u-kim')).toEqual(['CPU'])
  expect(visibleVersionBlocks('u-park')).toEqual(['GPU', 'DDR'])
  expect(visibleVersionBlocks('u-lee')).toEqual(['CPU', 'GPU', 'DDR'])
  expect(visibleVersionBlocks('missing-user')).toEqual([])
})

test('identical version names in different blocks remain independent when PoR changes', () => {
  const state = initialVersionState()
  const cpuSet = revisionSetOf(state, 'set-cpu-post-0')
  const gpuSet = revisionSetOf(state, 'set-gpu-post-1')
  gpuSet.netVer = cpuSet.netVer
  gpuSet.revision = cpuSet.revision
  const before = structuredClone(state)
  const next = assignPor(state, 'u-kim', cpuSet.id)
  expect(porOf(next, 'CPU')).toMatchObject({ revisionSetId: cpuSet.id, assignedBy: 'u-kim' })
  expect(porOf(next, 'GPU')).toEqual(porOf(before, 'GPU'))
  expect(porOf(next, 'DDR')).toEqual(porOf(before, 'DDR'))
  expect(next.runs).toEqual(before.runs)
  expect(next.snapshots).toEqual(before.snapshots)
  expect(state).toEqual(before)
  const cpuSnapshots = snapshotsFor(next, cpuSet.id)
  const gpuSnapshots = snapshotsFor(next, gpuSet.id)
  expect(cpuSnapshots.some(snapshot => gpuSnapshots.some(other => other.id === snapshot.id))).toBe(false)
  expect(assignPor(next, 'u-kim', cpuSet.id)).toBe(next)
})
