test('TOP sees independent block PoRs and viewing versions or ECOs does not designate a PoR', async ({ page }) => {
  const apiCalls: string[] = [], errors: string[] = []
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) apiCalls.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(path)
  const overview = page.getByRole('region', { name: '블록별 현재 PoR' })
  await expect(overview.locator('tbody tr')).toHaveCount(3)
  await expect(page.getByTestId('block-CPU')).toContainText('EVT0_ML4_DEV00')
  await expect(page.getByTestId('block-GPU')).toContainText('EVT0_ML3_DEV00')
  await expect(page.getByTestId('block-DDR')).toContainText('EVT0_ML2_DEV00')
  const initialPoRs = await overview.innerText()
  const context = page.getByRole('region', { name: '조회 중인 블록 버전' })
  await expect(context.locator('.vf-revision')).toHaveText(postRevision)
  await expect(page.getByRole('region', { name: 'ECO 목록' }).locator('tbody tr')).toHaveCount(4)
  await expect(page.getByRole('region', { name: '선택 버전의 sanity 결과' }).locator('.vf-result-missing')).toHaveCount(3)
  await page.screenshot({ path: 'artifacts/block-por-desktop.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'eco01 검사 결과 보기', exact: true }).click()
  await expect(page.getByTestId('run-Timing').locator('.vf-run-main .vf-result-pass')).toBeVisible()
  await expect(context.locator('.vf-revision')).toHaveText(postRevision)
  await page.getByRole('button', { name: 'EVT0_ML3_DEV00 버전 조회', exact: true }).click()
  await expect(page.getByTestId('run-Timing').locator('.vf-run-main .vf-result-fail')).toBeVisible()
  await page.getByTestId('run-Timing').getByText('실행 이력 1건', { exact: true }).click()
  await expect(page.getByTestId('run-Timing').locator('.vf-run-history .vf-result-fail')).toBeVisible()
  await expect(page.getByRole('button', { name: /PoR로 지정|최신 결과 검토 확인/ })).toHaveCount(0)
  expect(await overview.innerText()).toBe(initialPoRs)
  await expect(page.getByRole('button', { name: /PoR 구성 확정|새 PoR로 복사|Signoff 기록|현재 검사 결과 연결|ECO 추가|병합|합성 검사 추가|합성 실행 추가/ })).toHaveCount(0)
  expect(apiCalls).toEqual([])
  expect(errors).toEqual([])
})

