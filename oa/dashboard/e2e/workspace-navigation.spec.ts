import { test, expect } from '@playwright/test'

test('mobile drawer traps focus, hides closed navigation and returns focus on dismissal', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?demo=1&flow=legacy')
  await expect(page.getByText('CHECK-101', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '활동 이력', exact: true })).toHaveCount(0)
  const trigger = page.getByRole('button', { name: '메뉴 열기', exact: true })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: '워크스페이스 메뉴' })
  const first = drawer.getByRole('link', { name: 'Sanity Lens AI 홈', exact: true })
  const last = drawer.getByRole('button', { name: '연결 종료', exact: true })
  await expect(first).toBeFocused()
  await expect(page.getByRole('main')).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await last.focus()
  await page.keyboard.press('Tab')
  await expect(first).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(last).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')

  await trigger.click()
  await drawer.getByRole('button', { name: '활동 이력', exact: true }).click()
  await expect(page.getByRole('heading', { name: '검토 변경 이력' })).toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(page.getByRole('dialog', { name: '워크스페이스 메뉴' })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('button', { name: '활동 이력', exact: true })).toHaveCount(0)
})
