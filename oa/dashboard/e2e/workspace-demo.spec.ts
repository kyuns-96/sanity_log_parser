test('memory adapter enforces account scope, revision conflicts, idempotency and complete log partitions', async () => {
  const request = makeWorkspaceDemo()
  const overview = await request<WorkspaceOverview>('/overview')
  expect(overview.projects.map(project => project.name)).toEqual(['Atlas', 'Cygnus'])
  const block = overview.projects[0].blocks[0]
  const versions = await request<WorkspaceVersions>(`/blocks/${block.id}/versions`)
  const version = versions.items[0], base = `/blocks/${block.id}/versions/${version.id}/reports`
  const list = await request<WorkspaceReports>(base)
  const reportBase = `${base}/${list.items[0].id}`
  const task = await request<{ id: string }>(`${reportBase}/clustering/tasks`, { body: { expected_revision: 0 } })
  await request(`${reportBase}/clustering/tasks/step`, { body: { task_id: task.id, expected_chunk: 0 } })
  const workbench = await request<WorkbenchView>(`${reportBase}/workbench`)
  const groups = await request<PageResult<GroupBrief>>(`${reportBase}/clustering/groups`)
  const records = await request<GroupRecords>(`${reportBase}/clustering/records`)
  const move = { expected_revision: workbench.revision, request_id: 'one-demo-edit', operation: { kind: 'MOVE', record_ids: [records.items[0].id], destination_id: groups.items[1].id } }
  const edit = await request(`${reportBase}/clustering/operations`, { body: move })
  expect(await request(`${reportBase}/clustering/operations`, { body: move })).toEqual(edit)
  await expect(request(`${reportBase}/clustering/operations`, { body: { ...move, operation: { ...move.operation, record_ids: ['nonexistent-log'] } } })).rejects.toMatchObject({ code: 'REQUEST_CONFLICT' })
  await expect(request(`${reportBase}/clustering/operations`, { body: { ...move, request_id: 'stale-edit' } })).rejects.toMatchObject({ code: 'REVISION_CONFLICT' })
  const next = await request<WorkbenchView>(`${reportBase}/workbench`)
  await expect(request(`${reportBase}/clustering/operations`, { body: { expected_revision: next.revision, operation: { kind: 'MOVE', record_ids: ['nonexistent-log'], destination_id: groups.items[1].id } } })).rejects.toMatchObject({ code: 'INVALID_PARTITION' })
  const membership = (await Promise.all(groups.items.map(group => request<GroupRecords>(`${reportBase}/clustering/records?group_id=${group.id}`)))).flatMap(value => value.items.map(record => record.id))
  expect(membership.sort()).toEqual(records.items.map(record => record.id).sort())
  expect(new Set(membership).size).toBe(workbench.record_count)
  await expect(request(`${reportBase}/clustering`, { body: { expected_revision: next.revision, action: 'CONFIRM' } })).rejects.toMatchObject({ code: 'RATIONALE_REQUIRED' })
  for (const group of groups.items) {
    const head = await request<WorkbenchView>(`${reportBase}/workbench`)
    const members = await request<GroupRecords>(`${reportBase}/clustering/records?group_id=${group.id}`)
    await request(`${reportBase}/groups/${group.id}/rationale`, { body: { expected_revision: head.revision, action: 'SAVE', reviewed: true,
      content: { reason: '현재 그룹의 합성 로그와 구성을 확인했습니다.', evidence_ids: [members.items[0].id], reference_groups: [] }, reason: '로그 이동 이후 근거를 다시 확인했습니다.' } })
  }
  const ready = await request<WorkbenchView>(`${reportBase}/workbench`)
  await request(`${reportBase}/clustering`, { body: { expected_revision: ready.revision, action: 'CONFIRM' } })
  const confirmed = await request<WorkbenchView>(`${reportBase}/workbench`)
  await request(`${reportBase}/groups/${groups.items[0].id}/review`, { body: { expected_revision: 0, expected_cluster_revision: confirmed.revision, conclusion: 'PASS', reason: '도구 FAIL과 별도로 합성 예외 조건을 확인했습니다.' } })
  await request(`${reportBase}/clustering/operations`, { body: { expected_revision: confirmed.revision, operation: { kind: 'MERGE', group_ids: [groups.items[0].id, groups.items[1].id], destination_id: groups.items[1].id } } })
  const merged = await request<WorkbenchView>(`${reportBase}/workbench`)
  expect(merged.removed_count).toBe(1)
  expect(merged.report.check_status).toBe('FAIL')
  const prior = await request<ReportReview>(`${reportBase}/groups/${groups.items[0].id}/review`)
  expect(prior).toMatchObject({ can_review: false, current_stale: true, current: { conclusion: 'PASS' } })
  const top = await request<WorkspaceSession>('/demo/account', { body: { username: 'user01' } })
  expect(top.environment).toBe('MEMORY_DEMO')
  await expect(request(`/blocks/${block.id}/por`, { body: { version_id: version.id, expected_revision: 0, reason: 'TOP은 조회 전용입니다.' } })).rejects.toMatchObject({ code: 'FORBIDDEN' })
  await expect(request('/blocks/demo-cygnus-gpu/versions')).rejects.toMatchObject({ code: 'NOT_FOUND' })
})
