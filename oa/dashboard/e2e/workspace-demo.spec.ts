test('both explicit demo URLs open the current workspace without API, cookies or browser storage', async ({ page }) => {
  const calls: string[] = [], errors: string[] = []
  page.on('request', request => { if (new URL(request.url()).pathname.includes('/api/')) calls.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  for (const path of ['/?demo=1', demoUrl]) {
    await page.goto(path)
    await expect(page.getByRole('heading', { name: 'Atlas 프로젝트', exact: true })).toBeVisible()
    await expect(page.getByRole('region', { name: '워크스페이스 데모 안내' })).toContainText('새로고침하면 초기화')
    await expect(page.locator('.ws-connected')).toHaveText('데모 환경')
    await expect(page.locator('.ws-block-table tbody tr')).toHaveCount(1)
    await expect(page.locator('.ws-account')).toContainText('정민수')
    expect(new URL(page.url()).searchParams.get('demo')).toBe('1')
    expect(new URL(page.url()).pathname).toBe(path.startsWith('/workspace') ? '/workspace' : '/')
    expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
    expect(await page.context().cookies()).toEqual([])
  }
  expect(calls).toEqual([])
  expect(errors).toEqual([])
  await page.screenshot({ path: 'artifacts/workspace-demo-desktop.png', fullPage: true, animations: 'disabled' })
})

test('server errors remain errors until the user explicitly opens the workspace demo', async ({ page }) => {
  let calls = 0
  await page.route('**/workspace/api/**', route => { calls++; return route.fulfill({ status: 503, json: { code: 'DATABASE_UNAVAILABLE' } }) })
  await page.goto('/workspace')
  await expect(page.getByRole('alert')).toContainText('저장 서버에 연결하지 못했습니다.')
  await expect(page.getByRole('heading', { name: '워크스페이스에 로그인', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: '워크스페이스 데모 안내' })).toHaveCount(0)
  const before = calls
  await page.getByRole('button', { name: '데모 둘러보기', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Atlas 프로젝트', exact: true })).toBeVisible()
  expect(calls).toBe(before)
})

